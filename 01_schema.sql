-- =====================================================================
-- 01_schema.sql  |  Pharmacy Inventory, Expiry and Demand Forecasting DB
-- PostgreSQL 14+
-- Run on an empty database:  psql -d pharmacy -f 01_schema.sql
-- =====================================================================

DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;

-- ---------------------------------------------------------------------
-- Reference / master tables
-- ---------------------------------------------------------------------
CREATE TABLE categories (
    category_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60) NOT NULL UNIQUE,
    description   TEXT
);

CREATE TABLE suppliers (
    supplier_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    phone         VARCHAR(15)  NOT NULL UNIQUE,
    email         VARCHAR(100) UNIQUE,
    city          VARCHAR(60)  NOT NULL,
    CONSTRAINT chk_supplier_phone CHECK (phone ~ '^[0-9+ -]{8,15}$'),
    CONSTRAINT chk_supplier_email CHECK (email IS NULL OR email LIKE '%_@_%._%')
);

CREATE TABLE staff (
    staff_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    phone         VARCHAR(15)  UNIQUE,
    hired_on      DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT chk_staff_role CHECK (role IN ('pharmacist', 'cashier', 'manager'))
);

CREATE TABLE customers (
    customer_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    phone         VARCHAR(15)  NOT NULL UNIQUE,
    email         VARCHAR(100) UNIQUE,
    registered_on DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT chk_customer_phone CHECK (phone ~ '^[0-9+ -]{8,15}$')
);

-- ---------------------------------------------------------------------
-- Medicines and batches
-- A medicine is the product; a batch is one physical lot with its own
-- expiry date and remaining stock.
-- ---------------------------------------------------------------------
CREATE TABLE medicines (
    medicine_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(100) NOT NULL,
    generic_name          VARCHAR(100) NOT NULL,
    category_id           INT NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    manufacturer          VARCHAR(100) NOT NULL,
    unit_price            NUMERIC(10,2) NOT NULL CHECK (unit_price > 0),
    reorder_level         INT NOT NULL DEFAULT 50 CHECK (reorder_level >= 0),
    requires_prescription BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_medicine UNIQUE (name, manufacturer)
);

CREATE TABLE batches (
    batch_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id       INT NOT NULL REFERENCES medicines(medicine_id) ON DELETE RESTRICT,
    supplier_id       INT NOT NULL REFERENCES suppliers(supplier_id) ON DELETE RESTRICT,
    batch_no          VARCHAR(30) NOT NULL,
    quantity_in_stock INT NOT NULL CHECK (quantity_in_stock >= 0),
    purchase_price    NUMERIC(10,2) NOT NULL CHECK (purchase_price > 0),
    received_date     DATE NOT NULL DEFAULT CURRENT_DATE,
    expiry_date       DATE NOT NULL,
    CONSTRAINT uq_batch UNIQUE (medicine_id, batch_no),
    CONSTRAINT chk_batch_dates CHECK (expiry_date > received_date)
);

-- ---------------------------------------------------------------------
-- Sales
-- ---------------------------------------------------------------------
CREATE TABLE sales (
    sale_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   INT REFERENCES customers(customer_id) ON DELETE SET NULL,
    staff_id      INT NOT NULL REFERENCES staff(staff_id) ON DELETE RESTRICT,
    sale_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
    payment_mode  VARCHAR(10) NOT NULL DEFAULT 'cash',
    total_amount  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    CONSTRAINT chk_payment_mode CHECK (payment_mode IN ('cash', 'card', 'upi'))
);

CREATE TABLE sale_items (
    sale_item_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id       INT NOT NULL REFERENCES sales(sale_id) ON DELETE CASCADE,
    batch_id      INT NOT NULL REFERENCES batches(batch_id) ON DELETE RESTRICT,
    quantity      INT NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10,2) NOT NULL CHECK (unit_price > 0),
    CONSTRAINT uq_sale_batch UNIQUE (sale_id, batch_id)
);

-- ---------------------------------------------------------------------
-- Purchasing (optional module, safe to drop if time is short)
-- ---------------------------------------------------------------------
CREATE TABLE purchase_orders (
    po_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id   INT NOT NULL REFERENCES suppliers(supplier_id) ON DELETE RESTRICT,
    order_date    DATE NOT NULL DEFAULT CURRENT_DATE,
    status        VARCHAR(10) NOT NULL DEFAULT 'placed',
    CONSTRAINT chk_po_status CHECK (status IN ('placed', 'received', 'cancelled'))
);

CREATE TABLE purchase_order_items (
    po_item_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id         INT NOT NULL REFERENCES purchase_orders(po_id) ON DELETE CASCADE,
    medicine_id   INT NOT NULL REFERENCES medicines(medicine_id) ON DELETE RESTRICT,
    quantity      INT NOT NULL CHECK (quantity > 0),
    unit_cost     NUMERIC(10,2) NOT NULL CHECK (unit_cost > 0),
    CONSTRAINT uq_po_medicine UNIQUE (po_id, medicine_id)
);

-- ---------------------------------------------------------------------
-- AI module output and alerts
-- ---------------------------------------------------------------------
CREATE TABLE demand_forecasts (
    forecast_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id    INT NOT NULL REFERENCES medicines(medicine_id) ON DELETE CASCADE,
    forecast_month DATE NOT NULL,
    predicted_qty  INT NOT NULL CHECK (predicted_qty >= 0),
    method         VARCHAR(30) NOT NULL DEFAULT 'moving_average_3m',
    generated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_forecast UNIQUE (medicine_id, forecast_month),
    CONSTRAINT chk_forecast_month CHECK (EXTRACT(DAY FROM forecast_month) = 1)
);

CREATE TABLE stock_alerts (
    alert_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id   INT NOT NULL REFERENCES medicines(medicine_id) ON DELETE CASCADE,
    alert_type    VARCHAR(15) NOT NULL,
    message       TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved      BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_alert_type CHECK (alert_type IN ('low_stock', 'near_expiry', 'expired'))
);

-- ---------------------------------------------------------------------
-- Indexes (foreign keys and the columns the queries filter on)
-- ---------------------------------------------------------------------
CREATE INDEX idx_medicines_category   ON medicines(category_id);
CREATE INDEX idx_batches_medicine     ON batches(medicine_id);
CREATE INDEX idx_batches_expiry       ON batches(expiry_date) WHERE quantity_in_stock > 0;
CREATE INDEX idx_sales_date           ON sales(sale_date);
CREATE INDEX idx_sales_customer       ON sales(customer_id);
CREATE INDEX idx_sale_items_batch     ON sale_items(batch_id);
CREATE INDEX idx_alerts_open          ON stock_alerts(medicine_id) WHERE NOT resolved;

-- ---------------------------------------------------------------------
-- Views used by the app and the report
-- ---------------------------------------------------------------------
CREATE VIEW v_medicine_stock AS
SELECT m.medicine_id,
       m.name,
       c.name                                   AS category,
       m.reorder_level,
       COALESCE(SUM(b.quantity_in_stock)
                FILTER (WHERE b.expiry_date >= CURRENT_DATE), 0) AS sellable_stock,
       COALESCE(SUM(b.quantity_in_stock)
                FILTER (WHERE b.expiry_date <  CURRENT_DATE), 0) AS expired_stock
FROM medicines m
JOIN categories c        ON c.category_id = m.category_id
LEFT JOIN batches b      ON b.medicine_id = m.medicine_id
GROUP BY m.medicine_id, m.name, c.name, m.reorder_level;

CREATE VIEW v_low_stock AS
SELECT * FROM v_medicine_stock WHERE sellable_stock < reorder_level;

CREATE VIEW v_expiry_status AS
SELECT b.batch_id,
       m.name AS medicine,
       b.batch_no,
       b.quantity_in_stock,
       b.expiry_date,
       (b.expiry_date - CURRENT_DATE) AS days_left,
       CASE
           WHEN b.expiry_date <  CURRENT_DATE                        THEN 'expired'
           WHEN b.expiry_date <= CURRENT_DATE + 30                   THEN 'expires within 30 days'
           WHEN b.expiry_date <= CURRENT_DATE + 90                   THEN 'expires within 90 days'
           ELSE 'ok'
       END AS status
FROM batches b
JOIN medicines m ON m.medicine_id = b.medicine_id
WHERE b.quantity_in_stock > 0;
